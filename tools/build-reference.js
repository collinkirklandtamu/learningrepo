#!/usr/bin/env node
// Builds js/content/reference-<lang>.js from tools/reference-src/<lang>.js by running every example with the
// real interpreter and recording its output. Usage: node tools/build-reference.js [python|r]
// The reference test re-runs the examples and fails when the recorded output differs, so re-run this after editing a source file.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const SRC = path.join(__dirname, 'reference-src');
const OUT = path.join(__dirname, '..', 'js', 'content');

function entries(lang) {
  const src = require(path.join(SRC, lang + '.js'));
  const out = [];
  for (const [group, list] of Object.entries(src)) for (const [name, sig, desc, ex, lesson] of list) out.push({ name, sig, desc, group, ex, lesson });
  return out;
}

function runPython(list) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ref-py-'));
  for (const e of list) {
    const r = spawnSync('python3', ['-c', e.ex], { cwd: dir, encoding: 'utf8', timeout: 20000 });
    if (r.status !== 0) throw new Error(`python example failed for ${e.name}:\n${e.ex}\n${r.stderr}`);
    e.out = r.stdout.replace(/\s+$/, '');
  }
}

function runR(list) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ref-r-'));
  list.forEach((e, i) => fs.writeFileSync(path.join(dir, `ex${i}.R`), e.ex + '\n'));
  fs.writeFileSync(path.join(dir, 'run.R'), `setwd("${dir}")
for (i in seq_len(${list.length}) - 1L) {
  f <- sprintf("ex%d.R", i)
  res <- tryCatch(paste(capture.output(source(f, echo = FALSE, print.eval = TRUE, local = new.env())), collapse = "\\n"), error = function(e) paste0("ERROR: ", conditionMessage(e)))
  writeLines(res, sprintf("out%d.txt", i))
}
`);
  const r = spawnSync('Rscript', ['--vanilla', path.join(dir, 'run.R')], { encoding: 'utf8', timeout: 600000 });
  if (r.status !== 0) throw new Error('Rscript failed: ' + r.stderr);
  list.forEach((e, i) => {
    e.out = fs.readFileSync(path.join(dir, `out${i}.txt`), 'utf8').replace(/\s+$/, '');
    if (/^ERROR:/.test(e.out)) throw new Error(`R example failed for ${e.name}:\n${e.ex}\n${e.out}`);
  });
}

function write(lang, list) {
  const body = JSON.stringify(list.map((e) => ({ name: e.name, sig: e.sig, desc: e.desc, group: e.group, ex: e.ex, out: e.out, lesson: e.lesson })), null, 1);
  fs.writeFileSync(path.join(OUT, `reference-${lang}.js`), `// GENERATED by tools/build-reference.js from tools/reference-src/${lang}.js. Do not edit by hand.\n(function (root) {\n  'use strict';\n  const LP = (root.LP = root.LP || {});\n  (LP.reference = LP.reference || {}).${lang} = ${body};\n})(typeof window !== 'undefined' ? window : globalThis);\n`);
  console.log(`${lang}: ${list.length} entries`);
}

const only = process.argv[2];
for (const lang of ['python', 'r']) {
  if (only && only !== lang) continue;
  if (!fs.existsSync(path.join(SRC, lang + '.js'))) continue;
  const list = entries(lang);
  (lang === 'python' ? runPython : runR)(list);
  write(lang, list);
}
